import { NextResponse, type NextRequest } from "next/server";
import { can, crmAudit, getCrmViewer } from "@/lib/crm/auth";
import { getCrmConfig } from "@/lib/crm/config";
import { resolveRange } from "@/lib/crm/dates";
import { REPORTS, type Column, type ReportResult } from "@/lib/crm/reports";
import { toCsvRows, toXlsx, type Cell } from "@/lib/crm/xlsx";
import { createClient } from "@/lib/supabase/server";

/** Report export as Excel (.xlsx) or CSV. Same permissions as viewing the report, plus an export permission. */
export async function GET(request: NextRequest, ctx: RouteContext<"/api/crm/reports/[report]">) {
  const { report } = await ctx.params;
  const viewer = await getCrmViewer();
  if (!viewer) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  const sp = request.nextUrl.searchParams;
  const range = resolveRange({ range: sp.get("range") ?? undefined, from: sp.get("from") ?? undefined, to: sp.get("to") ?? undefined });
  const format = sp.get("format") === "csv" ? "csv" : "xlsx";
  const supabase = await createClient();
  const config = await getCrmConfig();

  let title: string;
  let result: ReportResult;
  if (report === "leads") {
    if (!can(viewer, "leads.export")) return NextResponse.json({ error: "Forbidden" }, { status: 403 });
    title = "Leads";
    result = await leadsExport(supabase, range, config);
  } else {
    const def = REPORTS.find((r) => r.key === report);
    const exportPerm = report.startsWith("expense") ? "expenses.export" : report === "payment_collection" || report === "outstanding" ? "payments.export" : "reports.export";
    if (!def || !def.permissions.every((p) => can(viewer, p)) || !(can(viewer, "reports.export") || can(viewer, exportPerm))) {
      return NextResponse.json({ error: "Forbidden" }, { status: 403 });
    }
    title = def.label;
    try {
      result = await def.build(supabase, range, config, viewer);
    } catch (err) {
      console.error("Report export failed", err);
      return NextResponse.json({ error: "Report failed" }, { status: 500 });
    }
  }

  const cell = (v: unknown, c: Column): Cell => (v === null || v === undefined ? "" : c.type && ["number", "money", "percent"].includes(c.type) ? Number(v) : String(v));
  const table: Cell[][] = [result.columns.map((c) => c.label), ...result.rows.map((r) => result.columns.map((c) => cell(r[c.key], c)))];
  const summary: Cell[][] = [["Report", title], ["Period", range.key === "all" ? "All time" : `${range.fromDate} to ${range.toDate}`], ["Generated", new Date().toISOString()], ["Generated by", viewer.fullName], [], ...result.summary.map((s) => [s.label, s.value] as Cell[])];
  const file = `${title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${range.fromDate}-to-${range.toDate}`;
  await crmAudit(viewer, "report.exported", "reports", report, { format, range: `${range.fromDate}..${range.toDate}`, rows: result.rows.length });

  if (format === "csv") {
    return new NextResponse(toCsvRows(table), { headers: { "Content-Type": "text/csv; charset=utf-8", "Content-Disposition": `attachment; filename="${file}.csv"`, "Cache-Control": "no-store" } });
  }
  const bytes = toXlsx([{ name: title, rows: table }, { name: "Summary", rows: summary }]);
  return new NextResponse(bytes as unknown as BodyInit, {
    headers: { "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "Content-Disposition": `attachment; filename="${file}.xlsx"`, "Cache-Control": "no-store" },
  });
}

async function leadsExport(db: Awaited<ReturnType<typeof createClient>>, range: ReturnType<typeof resolveRange>, config: Awaited<ReturnType<typeof getCrmConfig>>): Promise<ReportResult> {
  const rows: Record<string, string | number | null>[] = [];
  for (let from = 0; from < 50_000; from += 1000) {
    const { data } = await db.from("leads")
      .select("code, full_name, mobile, whatsapp, email, nationality, current_city, current_country, visa_type, destination_country, purpose_of_travel, source, campaign_name, temperature, stage_id, assigned_counsellor_id, next_follow_up_at, created_at, converted_at")
      .gte("created_at", range.from.toISOString()).lt("created_at", range.to.toISOString()).order("created_at", { ascending: false }).range(from, from + 999);
    for (const l of data ?? []) rows.push({
      ...l, visa_type: config.label("visa_category", l.visa_type), destination_country: config.label("destination_country", l.destination_country), source: config.label("lead_source", l.source),
      stage_id: l.stage_id ? config.stageById.get(l.stage_id)?.name ?? "" : "", assigned_counsellor_id: config.staffName(l.assigned_counsellor_id),
    });
    if (!data || data.length < 1000) break;
  }
  const cols: [string, string][] = [["code", "Lead ID"], ["full_name", "Name"], ["mobile", "Mobile"], ["whatsapp", "WhatsApp"], ["email", "Email"], ["nationality", "Nationality"], ["current_city", "City"], ["current_country", "Country"], ["visa_type", "Visa type"], ["destination_country", "Interested country"], ["purpose_of_travel", "Purpose"], ["source", "Source"], ["campaign_name", "Campaign"], ["temperature", "Priority"], ["stage_id", "Stage"], ["assigned_counsellor_id", "Assigned to"], ["next_follow_up_at", "Next follow-up"], ["created_at", "Created"], ["converted_at", "Converted"]];
  return { columns: cols.map(([key, label]) => ({ key, label })), rows, summary: [{ label: "Leads", value: rows.length }] };
}
